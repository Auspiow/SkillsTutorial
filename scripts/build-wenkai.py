"""Build locally hosted, on-demand WOFF2 slices from the official screen font.

Requires: pip install fonttools brotli
Usage: python scripts/build-wenkai.py path/to/LXGWWenKaiScreen.ttf
"""

import argparse
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets/fonts/lxgw-wenkai-screen"


def unicode_ranges(points):
    """Compact a sorted character set into CSS unicode-range intervals."""
    runs = []
    for point in sorted(points):
        if runs and runs[-1][1] + 1 == point:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ",".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in runs
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    args = parser.parse_args()
    with TTFont(args.font) as font:
        available = set(font.getBestCmap())

    # Keep the GB2312 first-level (3,755 frequently used Chinese characters)
    # together, then its remaining characters, then everything else upstream
    # supports. New lecture text never requires rebuilding these slices.
    common, gb2312 = set(), set()
    for high in range(0xA1, 0xF8):
        for low in range(0xA1, 0xFF):
            try:
                point = ord(bytes([high, low]).decode("gb2312"))
            except UnicodeDecodeError:
                continue
            gb2312.add(point)
            if 0xB0 <= high <= 0xD7:
                common.add(point)

    groups = [
        available & set(range(0x300)),
        available & common,
        (available & gb2312) - common - set(range(0x300)),
        available - gb2312 - set(range(0x300)),
    ]
    OUTPUT.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by scripts/build-wenkai.py; LXGW WenKai Screen v1.530. */"]
    count = 0
    for group in groups:
        points = sorted(group)
        for offset in range(0, len(points), 256):
            chars = points[offset:offset + 256]
            filename = f"screen-{count:03}.woff2"
            options = subset.Options()
            options.flavor = "woff2"
            options.recalc_timestamp = False
            font = subset.load_font(str(args.font), options)
            cutter = subset.Subsetter(options=options)
            cutter.populate(unicodes=chars)
            cutter.subset(font)
            subset.save_font(font, str(OUTPUT / filename), options)
            font.close()
            css.append(
                '@font-face {\n  font-family: "LXGW WenKai Screen";\n'
                f'  src: url("{filename}") format("woff2");\n'
                '  font-style: normal;\n  font-weight: 400;\n'
                '  font-display: swap;\n'
                f'  unicode-range: {unicode_ranges(chars)};\n}}'
            )
            count += 1
    (OUTPUT / "font.css").write_text("\n\n".join(css) + "\n", encoding="utf-8")
    print(f"Generated {count} slices covering {len(available)} codepoints.")


if __name__ == "__main__":
    main()
